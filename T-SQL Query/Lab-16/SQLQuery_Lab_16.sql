ON STADIUM.STADIUM_ID = TEAM.HOME_STADIUM_ID
GROUP BY STADIUM_CITY,TEAM_NAME

--12. Display team name and average matches played by players in each team.

SELECT TEAM_NAME, AVG(PLAYER_MATCHES_PLAYED) AS AVERAGE_MATCHES
FROM TEAM
INNER JOIN PLAYER
ON TEAM.TEAM_ID = PLAYER.TEAM_ID
GROUP BY TEAM_NAME

--13. Display team name and maximum matches played by any player in each team.

SELECT TEAM_NAME, MAX(PLAYER_MATCHES_PLAYED) AS MAX_MATCHES
FROM TEAM
INNER JOIN PLAYER
ON TEAM.TEAM_ID = PLAYER.TEAM_ID
GROUP BY TEAM_NAME

--14. Display team name and minimum matches played by any player in each team.

SELECT TEAM_NAME, MIN(PLAYER_MATCHES_PLAYED) AS MIN_MATCHES
FROM TEAM
INNER JOIN PLAYER
ON TEAM.TEAM_ID = PLAYER.TEAM_ID
GROUP BY TEAM_NAME

